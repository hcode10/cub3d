#include "libft.h"

int	ft_memcmp(const void *s1, const void *s2, size_t n)
{
	size_t	i;

	i = n;
	if (!n)
		return (0);
	while (i)
	{
		if (*((unsigned char *)s1) != *((unsigned char *)s2))
			return (*((unsigned char *)s1) - *((unsigned char *)s2));
		s1++;
		s2++;
		i--;
	}
	return (*((unsigned char *)s1 - n) - *((unsigned char *)s2 - n));
}
