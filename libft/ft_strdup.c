#include "libft.h"

char	*ft_strdup(const char *s)
{
	size_t		size_str;
	size_t		i;
	char		*str;

	size_str = ft_strlen(s);
	str = (char *)malloc(sizeof(char) * size_str + 1);
	if (!str)
		return (NULL);
	i = 0;
	while (s[i])
	{
		str[i] = s[i];
		i++;
	}
	str[i] = '\0';
	return (str);
}
